// write a code for add, subtract, and multiply two numbers in JavaScript

// add two numbers
function add(a, b) {
    return a + b;
}

// sub two numbers
function sub(a, b) {
    return a - b;
}

// mal two numbers
function mal(a, b){
    return a * b;
}
// Data
let a = 5;
let b = 10;

// Print output
// add two numbers
console.log("add two numbers")
console.log(add(a, b));

// add sub numbers
console.log("sub two numbers")
